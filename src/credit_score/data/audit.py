"""Data audit: cohort maturity and a first look at the performance target.

Writes ``docs/data_audit.md``. The numbers decide the temporal split and the
target definition, so the report is regenerated from data rather than typed.

The target proxy is defined in ``credit_score.target``.
"""

import argparse
from pathlib import Path

import pandas as pd

from credit_score.target import MONTHS_TO_90DPD, bad_within, charged_off

WINDOWS = (12, 18, 24)


def add_proxy_bad(df: pd.DataFrame) -> pd.DataFrame:
    """Add ``charged_off`` and one ``bad_<W>m`` flag per window in ``WINDOWS``."""
    df = df.copy()
    df["charged_off"] = charged_off(df)
    for w in WINDOWS:
        df[f"bad_{w}m"] = bad_within(df, w)
    return df


def cohort_table(df: pd.DataFrame, freq: str) -> pd.DataFrame:
    snapshot = df["last_pymnt_d"].max().to_period("M")
    cohort = df["issue_d"].dt.to_period(freq)
    grouped = df.groupby(cohort)
    out = pd.DataFrame({"loans": grouped.size()})
    out["months observed (min)"] = [(snapshot - p.asfreq("M", how="end")).n for p in out.index]
    out["% still open"] = grouped["loan_status"].agg(
        lambda s: s.str.contains("Current|Late|Grace").mean() * 100
    )
    out["% charged off"] = grouped["charged_off"].mean() * 100
    for w in WINDOWS:
        out[f"% bad {w}m"] = grouped[f"bad_{w}m"].mean() * 100
    out.index = out.index.astype(str)
    out.index.name = "issued"
    return out


def to_markdown(table: pd.DataFrame, decimals: int = 2) -> str:
    """Render a DataFrame as a Markdown table; whole numbers print without decimals."""

    def fmt(v):
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            return str(v)
        if float(v).is_integer():
            return f"{int(v):,}"
        return f"{v:,.{decimals}f}"

    header = [str(table.index.name), *map(str, table.columns)]
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    for idx, row in table.iterrows():
        lines.append("| " + " | ".join([str(idx), *(fmt(v) for v in row.tolist())]) + " |")
    return "\n".join(lines)


def build_report(accepted: pd.DataFrame, rejected: pd.DataFrame) -> str:
    df = add_proxy_bad(accepted)
    snapshot = df["last_pymnt_d"].max()
    recent = df[df["issue_d"] >= snapshot - pd.DateOffset(months=27)]
    nulls = (accepted.isna().mean() * 100).loc[lambda s: s > 0.5].sort_values(ascending=False)
    rej_nulls = (rejected.isna().mean() * 100).loc[lambda s: s > 0.5].sort_values(ascending=False)
    status = accepted["loan_status"].value_counts()
    return (
        "\n\n".join(
            [
                "# Data audit",
                "Generated by `make audit`. Do not edit by hand.",
                f"- Accepted loans: {len(accepted):,}, issued {accepted['issue_d'].min():%Y-%m} "
                f"to {accepted['issue_d'].max():%Y-%m}.\n"
                f"- Rejected applications: {len(rejected):,}, "
                f"{rejected['application_d'].min():%Y-%m} to "
                f"{rejected['application_d'].max():%Y-%m}.\n"
                f"- Snapshot month (latest payment seen): {snapshot:%Y-%m}.",
                "## Cohorts by issue year",
                "`% bad Wm` is the proxy described in `credit_score.target`: charged off, "
                f"with the last payment no later than month W − {MONTHS_TO_90DPD} on book. "
                "A cohort needs about W + 2 months of observation for it to be complete.",
                to_markdown(cohort_table(df, "Y")),
                "## Recent cohorts by issue month",
                to_markdown(cohort_table(recent, "M")),
                "## Loan status at snapshot",
                to_markdown(status.rename("loans").rename_axis("status").to_frame()),
                "## Missing values above 0.5%",
                "Accepted:",
                to_markdown(nulls.rename("% null").rename_axis("column").to_frame()),
                "Rejected:",
                to_markdown(rej_nulls.rename("% null").rename_axis("column").to_frame()),
            ]
        )
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/processed"))
    parser.add_argument("--out", type=Path, default=Path("docs/data_audit.md"))
    args = parser.parse_args()
    report = build_report(
        pd.read_parquet(args.data / "accepted.parquet"),
        pd.read_parquet(args.data / "rejected.parquet"),
    )
    args.out.write_text(report)
    print(f"Audit written to {args.out}")


if __name__ == "__main__":
    main()
