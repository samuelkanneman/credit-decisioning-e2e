"""Train the scorecard and its challenger, validate them and export the model.

``--dev-only`` fits and reports on development without touching the
out-of-time sample. Use it while changing code; the full run is the
evaluation and is meant to be read once.
"""

import argparse
import hashlib
import json
import os
import pickle
import subprocess
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd

from credit_score import challenger, scorecard, validation
from credit_score.config import TARGET
from credit_score.data.audit import to_markdown
from credit_score.metrics import psi_numeric

MODEL_VERSION = "scorecard-v1"
SUB_GRADES = [f"{g}{n}" for g in "ABCDEFG" for n in range(1, 6)]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git_commit() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def run(data: Path, models: Path, dev_only: bool = False) -> dict:
    df = pd.read_parquet(data / "modeling.parquet")
    process = pickle.loads((models / "binning.pkl").read_bytes())
    selected = json.loads((models / "selected_features.json").read_text())
    samples = {"dev": df[df["split"] == "dev"]}
    if not dev_only:
        samples["oot"] = df[df["split"] == "oot"]
    dev = samples["dev"]

    card, coefficients, dropped = scorecard.train(process, dev, selected, TARGET)
    card["version"] = MODEL_VERSION
    variables = [s["name"] for s in card["variables"]]
    constraints = challenger.monotone_constraints(card["variables"], variables)
    gbm = challenger.fit(dev, variables, TARGET, constraints)

    rank = {g: i for i, g in enumerate(SUB_GRADES)}
    scores = {
        "fico": {k: s["fico"].astype(float) for k, s in samples.items()},
        "lc_sub_grade": {k: -s["sub_grade"].map(rank).astype(float) for k, s in samples.items()},
        "scorecard": {k: scorecard.score(s, card).astype(float) for k, s in samples.items()},
        "lightgbm": {
            k: scorecard.score_from_pd(challenger.predict(gbm, s)) for k, s in samples.items()
        },
    }
    pds = {
        "scorecard": {
            k: scorecard.pd_from_score(v, card["calibration"])
            for k, v in scores["scorecard"].items()
        },
        "lightgbm": {k: challenger.predict(gbm, s) for k, s in samples.items()},
    }
    summary = validation.summary_table(samples, scores, TARGET)
    deciles = {
        (m, k): validation.decile_report(samples[k][TARGET], scores[m][k], pds[m][k])
        for m in pds
        for k in samples
    }
    bands = {
        k: validation.band_report(
            s[TARGET], scorecard.band(scores["scorecard"][k], card["bands"]), pds["scorecard"][k]
        )
        for k, s in samples.items()
    }
    out = {
        "card": card,
        "coefficients": coefficients,
        "dropped": dropped,
        "summary": summary,
        "deciles": deciles,
        "bands": bands,
        "gbm_search": pd.DataFrame(gbm["search"]).set_index("num_leaves"),
        "gbm_importance": challenger.importance(gbm, dev),
        "gbm": gbm,
    }
    if not dev_only:
        out["score_psi"] = psi_numeric(scores["scorecard"]["dev"], scores["scorecard"]["oot"])
        out["criteria"] = validation.check_criteria(
            summary, out["score_psi"], deciles[("scorecard", "oot")], coefficients
        )
    return out


def build_report(out: dict) -> str:
    card, summary = out["card"], out["summary"]
    parts = [
        "# Validation report",
        f"Generated by `make train`. Do not edit by hand. Model `{card['version']}`.",
        "Scores are oriented so that higher means lower risk. AUC is a fraction; KS is the "
        "canonical decile KS in percent; decile 1 is the riskiest. Lending Club's sub-grade is "
        "a reference, not a competitor: it uses information this model excludes.",
        "## Preregistered criteria",
        to_markdown(out["criteria"]),
        "## Discrimination",
        to_markdown(
            summary.set_axis([f"{m} / {s}" for m, s in summary.index]).rename_axis(
                "model / sample"
            ),
            decimals=4,
        ),
        f"Score PSI, development to out-of-time: {out['score_psi']:.4f}.",
        "## Scorecard deciles, out-of-time",
        to_markdown(out["deciles"][("scorecard", "oot")]),
        "## Scorecard deciles, development",
        to_markdown(out["deciles"][("scorecard", "dev")]),
        "## Risk bands",
        "Cut-offs are the quintiles of the development score and stay fixed.",
        "Out-of-time:",
        to_markdown(out["bands"]["oot"]),
        "Development:",
        to_markdown(out["bands"]["dev"]),
        "## Coefficients",
        to_markdown(out["coefficients"], decimals=4),
    ]
    if out["dropped"]:
        dropped = pd.Series(out["dropped"], name="reason").rename_axis("variable").to_frame()
        parts += ["Dropped during fitting:", to_markdown(dropped)]
    parts += [
        "## Points table",
        f"Scaling: {card['scaling']['base_score']:g} points at "
        f"{card['scaling']['base_odds']:g}:1 good:bad odds, "
        f"{card['scaling']['pdo']:g} points to double the odds.",
        to_markdown(scorecard.points_table(card)),
        "## Challenger",
        "LightGBM on the same variables with monotonic constraints. Cross-validation inside "
        "development, folds grouped by issue quarter:",
        to_markdown(out["gbm_search"], decimals=4),
        "Deciles, out-of-time:",
        to_markdown(out["deciles"][("lightgbm", "oot")]),
        "Mean absolute contribution to the log-odds (tree SHAP, development sample):",
        to_markdown(
            out["gbm_importance"].rename("mean |contribution|").rename_axis("variable").to_frame()
        ),
    ]
    return "\n\n".join(parts) + "\n"


def export(out: dict, data: Path, models: Path) -> Path:
    """Write the artifact the scoring API loads: the card plus its metadata."""
    target = models / out["card"]["version"]
    target.mkdir(parents=True, exist_ok=True)
    summary = out["summary"]
    metadata = {
        "model_version": out["card"]["version"],
        "trained_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "code_commit": _git_commit(),
        "data_sha256": {
            "modeling.parquet": _sha256(data / "modeling.parquet"),
            "binning.pkl": _sha256(models / "binning.pkl"),
        },
        "target": TARGET,
        "variables": [s["name"] for s in out["card"]["variables"]],
        "metrics": {
            f"{m}_{s}_{name}": float(summary.loc[(m, s), col])
            for m, s in summary.index
            for name, col in (("auc", "AUC"), ("ks", "KS deciles %"))
        }
        | {"scorecard_score_psi": out["score_psi"]},
        "criteria_met": out["criteria"]["met"].eq("yes").to_dict(),
    }
    (target / "card.json").write_text(json.dumps(out["card"], indent=2) + "\n")
    (target / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    out["gbm"]["booster"].save_model(target / "challenger_lightgbm.txt")
    return target


def log_to_mlflow(artifact_dir: Path, report: Path) -> None:
    import mlflow

    metadata = json.loads((artifact_dir / "metadata.json").read_text())
    mlflow.set_tracking_uri(os.environ.get("MLFLOW_TRACKING_URI", "sqlite:///mlflow.db"))
    mlflow.set_experiment("credit-scorecard")
    with mlflow.start_run(run_name=metadata["model_version"]):
        mlflow.log_params(
            {
                "model_version": metadata["model_version"],
                "code_commit": metadata["code_commit"],
                "target": metadata["target"],
                "n_variables": len(metadata["variables"]),
                **{f"sha256_{k}": v for k, v in metadata["data_sha256"].items()},
            }
        )
        mlflow.log_metrics(metadata["metrics"])
        mlflow.log_artifacts(str(artifact_dir), artifact_path="model")
        mlflow.log_artifact(str(report))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/processed"))
    parser.add_argument("--models", type=Path, default=Path("models"))
    parser.add_argument("--report", type=Path, default=Path("docs/validation_report.md"))
    parser.add_argument("--dev-only", action="store_true")
    parser.add_argument("--no-mlflow", action="store_true")
    args = parser.parse_args()
    np.random.seed(42)

    out = run(args.data, args.models, dev_only=args.dev_only)
    pd.set_option("display.width", 200)
    print(out["coefficients"].round(4).to_string())
    print("dropped:", out["dropped"] or "none")
    print(out["summary"].round(4).to_string())
    print(out["gbm_search"].to_string())
    if args.dev_only:
        print(out["deciles"][("scorecard", "dev")].round(2).to_string())
        return
    print(out["criteria"].to_string())
    args.report.write_text(build_report(out))
    artifact_dir = export(out, args.data, args.models)
    if not args.no_mlflow:
        log_to_mlflow(artifact_dir, args.report)
    print(f"Model exported to {artifact_dir}, report in {args.report}")


if __name__ == "__main__":
    main()
